/**
 * Marklet core · anchor engine
 *
 *  1. ElementPicker   – hover highlight + info tooltip, click to pick (pure DOM, no framework).
 *  2. generateAnchor  – composite anchor: data-testid → id → semantic CSS → structural path,
 *                       plus tagName, first-30-char text and relative bounding box.
 *  3. resolveAnchor   – find the element again, validating with tag/text, with fuzzy fallbacks.
 *
 * Must stay free of chrome.* APIs (enforced by scripts/check-layers.mjs).
 */
import type { AnchorBoundingBox, AnchorOverlayContext, AnchorStrategy, ElementAnchor } from '../adapters/types';

/* ================================================================== */
/* Helpers                                                            */
/* ================================================================== */

export const TEST_ID_ATTRS = ['data-testid', 'data-test-id', 'data-test', 'data-qa', 'data-cy'] as const;
const FUZZY_ATTRS = ['role', 'name', 'aria-label', 'type', 'placeholder', 'href', 'title', 'alt', 'for'] as const;
const TEXT_SNIPPET_LEN = 30;

const cssEscape = (v: string): string =>
  typeof CSS !== 'undefined' && CSS.escape ? CSS.escape(v) : v.replace(/[^a-zA-Z0-9_-]/g, (c) => `\\${c}`);

const attrValue = (v: string): string => `"${v.replace(/["\\]/g, '\\$&')}"`;

const isElement = (n: unknown): n is Element => !!n && (n as Node).nodeType === 1;

export function getTestId(el: Element): { attr: string; value: string } | null {
  for (const attr of TEST_ID_ATTRS) {
    const value = el.getAttribute(attr);
    if (value) return { attr, value };
  }
  return null;
}

/** Heuristic: ids that look generated by frameworks are not stable anchors. */
export function isStableId(id: string): boolean {
  if (!id || id.length > 64) return false;
  if (/^\d/.test(id)) return false;
  if (/^:r[0-9a-z]*:$/i.test(id)) return false; // React useId
  if (/^(ember|react|radix|headlessui|mui|rc[-_]|__|vue-|ng-|ext-gen)/i.test(id)) return false;
  if (/\d{4,}/.test(id)) return false;
  if (/[0-9a-f]{8,}/i.test(id) && /\d/.test(id)) return false;
  return true;
}

const STATE_CLASS =
  /^(is-|has-)?(active|hover|focus(ed)?|open(ed)?|selected|show(n)?|visible|hidden|disabled|collapsed|expanded|current|checked)$/i;

/** Heuristic: drop hashed / utility / state classes from semantic selectors. */
export function isStableClass(c: string): boolean {
  if (!c || c.length > 40) return false;
  if (/[:[\]/@!%]/.test(c)) return false; // tailwind variants & arbitrary values
  if (/^(css|sc|jsx|emotion|svelte|styled|chakra|mantine)-/i.test(c)) return false;
  if (/__[a-zA-Z0-9_-]{5,}$/.test(c) && /\d/.test(c)) return false; // CSS modules hash
  if (/[a-zA-Z]+[0-9]+[a-zA-Z0-9]*[0-9]/.test(c) && /[A-Z]/.test(c) && c.length >= 6) return false; // random-ish
  if (STATE_CLASS.test(c)) return false;
  if (c.startsWith('marklet')) return false;
  return true;
}

function isUniqueMatch(selector: string, el: Element, root: ParentNode): boolean {
  try {
    const found = root.querySelectorAll(selector);
    return found.length === 1 && found[0] === el;
  } catch {
    return false;
  }
}

function safeQuery(selector: string, root: ParentNode): Element | null {
  try {
    return root.querySelector(selector);
  } catch {
    return null;
  }
}

function nthOfType(el: Element): { index: number; total: number } {
  const parent = el.parentElement;
  if (!parent) return { index: 1, total: 1 };
  let index = 0;
  let total = 0;
  for (const sib of Array.from(parent.children)) {
    if (sib.tagName === el.tagName) {
      total++;
      if (sib === el) index = total;
    }
  }
  return { index, total };
}

/** Selector segment for one element, using only "meaningful" signals. */
function semanticSegment(el: Element): { seg: string; anchored: boolean } {
  const tag = el.tagName.toLowerCase();
  const tid = getTestId(el);
  if (tid) return { seg: `${tag}[${tid.attr}=${attrValue(tid.value)}]`, anchored: true };
  if (el.id && isStableId(el.id)) return { seg: `#${cssEscape(el.id)}`, anchored: true };

  let seg = tag;
  const role = el.getAttribute('role');
  const name = el.getAttribute('name');
  const type = el.getAttribute('type');
  const aria = el.getAttribute('aria-label');
  if (name && /^(input|select|textarea|button|form|fieldset|iframe)$/.test(tag)) seg += `[name=${attrValue(name)}]`;
  else if (type && tag === 'input') seg += `[type=${attrValue(type)}]`;
  if (role) seg += `[role=${attrValue(role)}]`;
  else if (aria && aria.length <= 40) seg += `[aria-label=${attrValue(aria)}]`;

  const classes = Array.from(el.classList).filter(isStableClass).slice(0, 2);
  seg += classes.map((c) => `.${cssEscape(c)}`).join('');
  return { seg, anchored: false };
}

/** Semantic selector: climbs ancestors until the chain is unique in `root`. */
export function buildSemanticSelector(el: Element, root: ParentNode = document, maxDepth = 8): string {
  const parts: string[] = [];
  let cur: Element | null = el;
  let depth = 0;
  while (cur && cur.tagName !== 'HTML' && depth < maxDepth) {
    const { seg, anchored } = semanticSegment(cur);
    let candidate = [seg, ...parts].join(' > ');
    if (isUniqueMatch(candidate, el, root)) return candidate;

    let finalSeg = seg;
    if (!anchored) {
      const { index, total } = nthOfType(cur);
      if (total > 1) {
        finalSeg = `${seg}:nth-of-type(${index})`;
        candidate = [finalSeg, ...parts].join(' > ');
        if (isUniqueMatch(candidate, el, root)) return candidate;
      }
    }
    parts.unshift(finalSeg);
    cur = cur.parentElement;
    depth++;
  }
  return parts.join(' > ');
}

/** Purely structural path from <body>, every step with :nth-of-type – always resolvable. */
export function buildPathSelector(el: Element): string {
  const parts: string[] = [];
  let cur: Element | null = el;
  while (cur && cur.tagName !== 'BODY' && cur.tagName !== 'HTML') {
    const { index } = nthOfType(cur);
    parts.unshift(`${cur.tagName.toLowerCase()}:nth-of-type(${index})`);
    cur = cur.parentElement;
  }
  parts.unshift('body');
  return parts.join(' > ');
}

const collapse = (s: string) => s.replace(/\s+/g, ' ').trim();

/** First 30 visible characters – form fields fall back to placeholder / label / value. */
export function getTextSnippet(el: Element): string {
  const tag = el.tagName;
  let text = '';
  if (tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT') {
    const f = el as HTMLInputElement;
    text = f.getAttribute('placeholder') || f.getAttribute('aria-label') || (f.type !== 'password' ? f.value : '') || f.name || '';
  } else if (tag === 'IMG') {
    text = el.getAttribute('alt') || '';
  } else {
    text = (el as HTMLElement).innerText ?? el.textContent ?? '';
    if (!collapse(text)) text = el.getAttribute('aria-label') || el.getAttribute('title') || '';
  }
  return collapse(text).slice(0, TEXT_SNIPPET_LEN);
}

function getDocSize() {
  const de = document.documentElement;
  const body = document.body;
  return {
    docWidth: Math.max(de.scrollWidth, body?.scrollWidth ?? 0, de.clientWidth),
    docHeight: Math.max(de.scrollHeight, body?.scrollHeight ?? 0, de.clientHeight),
  };
}

export function captureBoundingBox(el: Element): AnchorBoundingBox {
  const r = el.getBoundingClientRect();
  const { docWidth, docHeight } = getDocSize();
  const pageX = r.left + window.scrollX;
  const pageY = r.top + window.scrollY;
  const round = (n: number) => Math.round(n * 10000) / 10000;
  return {
    pageX: Math.round(pageX),
    pageY: Math.round(pageY),
    width: Math.round(r.width),
    height: Math.round(r.height),
    xRatio: round(pageX / docWidth),
    yRatio: round(pageY / docHeight),
    widthRatio: round(r.width / docWidth),
    heightRatio: round(r.height / docHeight),
    docWidth,
    docHeight,
    viewportWidth: window.innerWidth,
    viewportHeight: window.innerHeight,
  };
}

function collectAttributes(el: Element): Record<string, string> | undefined {
  const out: Record<string, string> = {};
  for (const a of FUZZY_ATTRS) {
    const v = el.getAttribute(a);
    if (v) out[a] = v.slice(0, 120);
  }
  return Object.keys(out).length ? out : undefined;
}

/** Detect whether `el` sits inside a modal, native <dialog>, drawer, or <details> panel. */
export function detectOverlayContext(el: Element): AnchorOverlayContext | undefined {
  const details = el.closest('details');
  if (details && !el.closest('summary')) {
    const summary = details.querySelector(':scope > summary');
    return {
      kind: 'collapsible',
      title: summary ? collapse(summary.textContent ?? '').slice(0, 60) || undefined : undefined,
    };
  }

  const overlay = el.closest('dialog, [role="dialog"], [aria-modal="true"], .modal, .drawer');
  if (!overlay) return undefined;

  const isDrawer =
    overlay.classList.contains('drawer') ||
    overlay.classList.contains('drawer-backdrop') ||
    /drawer|sheet/i.test(overlay.id + ' ' + overlay.className);

  let title: string | undefined;
  const labelledBy = overlay.getAttribute('aria-labelledby');
  if (labelledBy) {
    const labelEl = document.getElementById(labelledBy);
    if (labelEl) title = collapse(labelEl.textContent ?? '').slice(0, 60) || undefined;
  }
  if (!title) {
    const heading = overlay.querySelector('h1, h2, h3, [role="heading"]');
    if (heading) title = collapse(heading.textContent ?? '').slice(0, 60) || undefined;
  }
  if (!title) {
    title = overlay.getAttribute('aria-label') || undefined;
  }

  return { kind: isDrawer ? 'drawer' : 'dialog', title };
}

/* ================================================================== */
/* Anchor generation                                                  */
/* ================================================================== */

export function generateAnchor(el: Element, root: ParentNode = document): ElementAnchor {
  const tid = getTestId(el);
  const pathSelector = buildPathSelector(el);
  let strategy: AnchorStrategy;
  let selector: string;

  const tidSelector = tid ? `[${tid.attr}=${attrValue(tid.value)}]` : '';
  const idSelector = el.id && isStableId(el.id) ? `#${cssEscape(el.id)}` : '';

  if (tid && isUniqueMatch(tidSelector, el, root)) {
    strategy = 'testid';
    selector = tidSelector;
  } else if (idSelector && isUniqueMatch(idSelector, el, root)) {
    strategy = 'id';
    selector = idSelector;
  } else {
    const semantic = buildSemanticSelector(el, root);
    if (semantic && isUniqueMatch(semantic, el, root)) {
      strategy = 'semantic';
      selector = semantic;
    } else {
      strategy = 'path';
      selector = pathSelector;
    }
  }

  return {
    strategy,
    selector,
    pathSelector,
    testId: tid?.value,
    testIdAttr: tid?.attr,
    elementId: el.id || undefined,
    tagName: el.tagName.toLowerCase(),
    textSnippet: getTextSnippet(el),
    attributes: collectAttributes(el),
    overlayContext: detectOverlayContext(el),
    boundingBox: captureBoundingBox(el),
  };
}

/* ================================================================== */
/* Anchor resolution                                                  */
/* ================================================================== */

export interface ResolvedAnchor {
  element: Element | null;
  /** Which signal actually found the element. */
  matchedBy: AnchorStrategy | 'text' | 'none';
  /** 0..1 – UI can flag low-confidence or orphaned pins. */
  confidence: number;
}

function textMatches(el: Element, snippet: string): boolean {
  if (!snippet) return true;
  const now = getTextSnippet(el);
  if (!now) return false;
  return now === snippet || now.startsWith(snippet.slice(0, 12)) || snippet.startsWith(now.slice(0, 12));
}

export function resolveAnchor(anchor: ElementAnchor, root: ParentNode = document): ResolvedAnchor {
  const tag = anchor.tagName.toUpperCase();
  const candidates: Array<{ sel: string; by: AnchorStrategy; base: number; strictText: boolean }> = [];

  if (anchor.testId && anchor.testIdAttr) {
    candidates.push({ sel: `[${anchor.testIdAttr}=${attrValue(anchor.testId)}]`, by: 'testid', base: 1, strictText: false });
  }
  if (anchor.elementId) {
    candidates.push({ sel: `#${cssEscape(anchor.elementId)}`, by: 'id', base: 0.95, strictText: false });
  }
  if (anchor.strategy === 'semantic') {
    candidates.push({ sel: anchor.selector, by: 'semantic', base: 0.85, strictText: false });
  }
  candidates.push({ sel: anchor.pathSelector, by: 'path', base: 0.6, strictText: true });

  for (const c of candidates) {
    const el = safeQuery(c.sel, root);
    if (!el || el.tagName !== tag) continue;
    const textOk = textMatches(el, anchor.textSnippet);
    if (!textOk && c.strictText) continue;
    return { element: el, matchedBy: c.by, confidence: textOk ? c.base : c.base * 0.7 };
  }

  // Fuzzy fallback: same tag + same text, nearest to the original position.
  if (anchor.textSnippet.length >= 2) {
    const bb = anchor.boundingBox;
    let best: Element | null = null;
    let bestDist = Infinity;
    for (const el of Array.from(root.querySelectorAll(anchor.tagName))) {
      if (getTextSnippet(el) !== anchor.textSnippet) continue;
      const r = el.getBoundingClientRect();
      const d = Math.hypot(r.left + window.scrollX - bb.pageX, r.top + window.scrollY - bb.pageY);
      if (d < bestDist) {
        bestDist = d;
        best = el;
      }
    }
    if (best) return { element: best, matchedBy: 'text', confidence: 0.5 };
  }

  return { element: null, matchedBy: 'none', confidence: 0 };
}

/** Short human-readable label, e.g. `button#submit.btn.primary`. */
export function describeElement(el: Element): string {
  const tag = el.tagName.toLowerCase();
  const tid = getTestId(el);
  if (tid) return `${tag}[${tid.attr}="${tid.value}"]`;
  const id = el.id ? `#${el.id}` : '';
  const cls = Array.from(el.classList)
    .filter((c) => !c.startsWith('marklet'))
    .slice(0, 3)
    .map((c) => `.${c}`)
    .join('');
  return `${tag}${id}${cls}`;
}

/* ================================================================== */
/* Element picker                                                     */
/* ================================================================== */

export interface PickResult {
  element: Element;
  anchor: ElementAnchor;
}

export interface ElementPickerOptions {
  /** Container (ideally inside a Shadow DOM) where highlight box & tooltip are rendered. */
  layer: HTMLElement | ShadowRoot;
  /** Our own UI host – events from inside it are ignored (never picked, never blocked). */
  ignoreHost?: Element;
  onPick: (result: PickResult) => void;
  onCancel?: () => void;
  accentColor?: string;
  /** Root used for uniqueness checks (defaults to document). */
  root?: ParentNode;
}

const CURSOR_STYLE_ID = 'marklet-picker-cursor';
const BLOCKED_EVENTS = ['mousedown', 'mouseup', 'pointerdown', 'pointerup', 'dblclick', 'contextmenu', 'auxclick'] as const;

/**
 * Hover → highlight + tooltip (tag/id/class, size, anchor hint). Click → pick.
 * ↑ / ↓ walk to parent / back to child. Esc cancels.
 */
export class ElementPicker {
  private opts: ElementPickerOptions;
  private active = false;
  private current: Element | null = null;
  private childStack: Element[] = [];
  private box: HTMLDivElement | null = null;
  private tip: HTMLDivElement | null = null;
  private raf = 0;

  constructor(opts: ElementPickerOptions) {
    this.opts = opts;
  }

  get isActive(): boolean {
    return this.active;
  }

  start(): void {
    if (this.active) return;
    this.active = true;
    this.mountVisuals();
    window.addEventListener('mousemove', this.onMove, true);
    window.addEventListener('click', this.onClick, true);
    window.addEventListener('keydown', this.onKey, true);
    window.addEventListener('scroll', this.onScroll, true);
    window.addEventListener('resize', this.onScroll);
    BLOCKED_EVENTS.forEach((t) => window.addEventListener(t, this.block, true));
    this.setCursor(true);
  }

  stop(): void {
    if (!this.active) return;
    this.active = false;
    window.removeEventListener('mousemove', this.onMove, true);
    window.removeEventListener('click', this.onClick, true);
    window.removeEventListener('keydown', this.onKey, true);
    window.removeEventListener('scroll', this.onScroll, true);
    window.removeEventListener('resize', this.onScroll);
    BLOCKED_EVENTS.forEach((t) => window.removeEventListener(t, this.block, true));
    cancelAnimationFrame(this.raf);
    this.setCursor(false);
    this.box?.remove();
    this.tip?.remove();
    this.box = this.tip = null;
    this.current = null;
    this.childStack = [];
  }

  /* ---------------- internals ---------------- */

  private isOwnEvent(e: Event): boolean {
    const host = this.opts.ignoreHost;
    return !!host && e.composedPath().includes(host);
  }

  private targetOf(e: Event): Element | null {
    const t = e.composedPath()[0];
    if (!isElement(t)) return null;
    if (t.tagName === 'HTML' || t.tagName === 'BODY') return null;
    return t;
  }

  private onMove = (e: MouseEvent) => {
    if (this.isOwnEvent(e)) {
      this.highlight(null);
      return;
    }
    const t = this.targetOf(e);
    if (t !== this.current) {
      this.childStack = [];
      this.highlight(t);
    }
  };

  private onScroll = () => {
    cancelAnimationFrame(this.raf);
    this.raf = requestAnimationFrame(() => this.highlight(this.current));
  };

  private block = (e: Event) => {
    if (this.isOwnEvent(e)) return;
    e.preventDefault();
    e.stopPropagation();
    e.stopImmediatePropagation();
  };

  private onClick = (e: MouseEvent) => {
    if (this.isOwnEvent(e)) return;
    e.preventDefault();
    e.stopPropagation();
    e.stopImmediatePropagation();
    const el = this.current ?? this.targetOf(e);
    if (!el) return;
    const anchor = generateAnchor(el, this.opts.root ?? document);
    this.stop();
    this.opts.onPick({ element: el, anchor });
  };

  private onKey = (e: KeyboardEvent) => {
    if (e.key === 'Escape') {
      e.preventDefault();
      e.stopPropagation();
      this.stop();
      this.opts.onCancel?.();
      return;
    }
    if (!this.current) return;
    if (e.key === 'ArrowUp') {
      const parent = this.current.parentElement;
      if (parent && parent.tagName !== 'BODY' && parent.tagName !== 'HTML') {
        e.preventDefault();
        this.childStack.push(this.current);
        this.highlight(parent);
      }
    } else if (e.key === 'ArrowDown') {
      const child = this.childStack.pop();
      if (child) {
        e.preventDefault();
        this.highlight(child);
      }
    } else if (e.key === 'Enter') {
      e.preventDefault();
      const el = this.current;
      const anchor = generateAnchor(el, this.opts.root ?? document);
      this.stop();
      this.opts.onPick({ element: el, anchor });
    }
  };

  private mountVisuals() {
    const accent = this.opts.accentColor ?? '#c96442';
    const box = document.createElement('div');
    box.setAttribute('data-marklet', 'picker-box');
    Object.assign(box.style, {
      position: 'fixed',
      pointerEvents: 'none',
      zIndex: '2147483646',
      border: `1.5px solid ${accent}`,
      background: 'rgba(217, 119, 87, 0.09)',
      borderRadius: '2px',
      boxSizing: 'border-box',
      transition: 'all 50ms ease-out',
      display: 'none',
    } satisfies Partial<CSSStyleDeclaration>);

    const tip = document.createElement('div');
    tip.setAttribute('data-marklet', 'picker-tip');
    Object.assign(tip.style, {
      position: 'fixed',
      pointerEvents: 'none',
      zIndex: '2147483647',
      background: '#292524',
      color: '#f5f3ee',
      font: '500 11px/1.35 Inter, -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif',
      padding: '3px 7px',
      borderRadius: '4px',
      boxShadow: '0 2px 8px rgba(0, 0, 0, 0.18)',
      whiteSpace: 'nowrap',
      maxWidth: '400px',
      overflow: 'hidden',
      textOverflow: 'ellipsis',
      display: 'none',
    } satisfies Partial<CSSStyleDeclaration>);

    this.opts.layer.appendChild(box);
    this.opts.layer.appendChild(tip);
    this.box = box;
    this.tip = tip;
  }

  private highlight(el: Element | null) {
    this.current = el;
    const { box, tip } = this;
    if (!box || !tip) return;
    if (!el) {
      box.style.display = tip.style.display = 'none';
      return;
    }
    const r = el.getBoundingClientRect();
    Object.assign(box.style, {
      display: 'block',
      left: `${r.left}px`,
      top: `${r.top}px`,
      width: `${r.width}px`,
      height: `${r.height}px`,
    });

    const tid = getTestId(el);
    const hint = tid ? 'testid' : el.id && isStableId(el.id) ? 'id' : 'selector';
    tip.textContent = '';
    const label = document.createElement('span');
    label.textContent = describeElement(el);
    label.style.fontWeight = '600';
    const meta = document.createElement('span');
    meta.textContent = `  ${Math.round(r.width)} × ${Math.round(r.height)} · ${hint}`;
    meta.style.opacity = '0.88';
    tip.append(label, meta);
    tip.style.display = 'block';

    const tipH = 22;
    const top = r.top - tipH - 6 >= 0 ? r.top - tipH - 6 : Math.min(r.bottom + 6, window.innerHeight - tipH - 4);
    const left = Math.max(4, Math.min(r.left, window.innerWidth - 404));
    tip.style.top = `${top}px`;
    tip.style.left = `${left}px`;
  }

  private setCursor(on: boolean) {
    const existing = document.getElementById(CURSOR_STYLE_ID);
    if (!on) {
      existing?.remove();
      return;
    }
    if (existing) return;
    const style = document.createElement('style');
    style.id = CURSOR_STYLE_ID;
    style.textContent = '*{cursor:crosshair !important}';
    (document.head ?? document.documentElement).appendChild(style);
  }
}
